/*
 * InstUI Icon Generator for Android
 *
 * Generates one Compose ImageVector Kotlin file per icon under:
 *   ../src/main/java/com/instructure/instui/token/icon/
 *
 * Sources:
 * - Lucide icons via the `lucide` npm package (pinned in package.json)
 * - instructure-ui Custom icons downloaded from GitHub (pinned via
 *   CUSTOM_ICONS_VERSION passed in by build-instui.js)
 *
 * Custom icons that share a camelCase name with a Lucide icon are suffixed
 * with "Custom" (e.g. searchCustom). The output directory is cleared on each
 * run; there is no delta/manifest.
 */

