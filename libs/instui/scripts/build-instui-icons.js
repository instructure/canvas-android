/**
 * @param {function} download  download(url, options) helper from build-instui.js
 * @param {string}   customVer instructure-ui version for Custom icons
 */
async function buildIcons(download, customVer) {
  // Generate into a sibling tmp dir, then atomically swap with the real output.
  // This way a failure mid-generation (e.g. GitHub rate-limit on Custom icons)
  // leaves the existing checked-in icon set intact.
  const TMP_DIR = `${BUILD_DIR}.tmp`
  if (fs.existsSync(TMP_DIR)) {
    fs.rmSync(TMP_DIR, { recursive: true, force: true })
  }
  fs.mkdirSync(TMP_DIR, { recursive: true })

  // Top-level accessor object
  fs.writeFileSync(path.join(TMP_DIR, 'InstUIIcons.kt'), generateAccessorObject())

  // Lucide LICENSE alongside the module
  const lucideLicense = fs.readFileSync(path.join(__dirname, 'node_modules/lucide/LICENSE'), 'utf8')
  fs.writeFileSync(LUCIDE_LICENSE_OUT, lucideLicense)

  const usedNames = new Set()
  let lucideCount = 0
  let customCount = 0

  // Lucide ships alias pairs that only differ by letter case (e.g. ArrowDownAZ /
  // ArrowDownAz, Axis3D / Axis3d) — same icon body, different exported name.
  // These collide on case-insensitive filesystems (macOS APFS), so we pick the
  // form with more uppercase letters as canonical and drop the other. If a
  // future Lucide release ever ships a case-collision pair with diverging icon
  // bodies, fail loudly instead of silently dropping one.
  const lucideByFilename = new Map()
  const uppers = s => (s.match(/[A-Z]/g) || []).length
  for (const key of Object.keys(lucide.icons)) {
    const fileKey = toPascalCase(key).toLowerCase()
    const prior = lucideByFilename.get(fileKey)
    if (!prior) {
      lucideByFilename.set(fileKey, key)
      continue
    }
    if (JSON.stringify(lucide.icons[key]) !== JSON.stringify(lucide.icons[prior])) {
      throw new Error(
        `Lucide case-alias collision with diverging icon data: ${prior} vs ${key}. ` +
        `Cannot safely dedup; update the generator to handle this case.`
      )
    }
    if (uppers(key) > uppers(prior)) lucideByFilename.set(fileKey, key)
  }
  const lucideKeys = [...lucideByFilename.values()].sort()
  console.log(`  Generating ${lucideKeys.length} Lucide icons...`)
  for (const key of lucideKeys) {
    const camel = toCamelCase(key)
    const pascal = toPascalCase(key)
    const code = generateLucideKotlin(camel, pascal, lucide.icons[key])
    fs.writeFileSync(path.join(TMP_DIR, `${pascal}.kt`), code)
    usedNames.add(camel)
    lucideCount++
  }

  // instructure-ui Custom icons (kebab-case filenames in upstream)
  console.log(`  Fetching Custom icons from instructure-ui ${customVer}...`)
  const customSvgs = await fetchCustomIcons(customVer, download)
  const customNames = Object.keys(customSvgs).sort()
  console.log(`  Generating ${customNames.length} Custom icons...`)
  for (const baseName of customNames) {
    let camel = toCamelCase(baseName)
    let pascal = toPascalCase(baseName)
    if (usedNames.has(camel)) {
      camel = `${camel}Custom`
      pascal = `${pascal}Custom`
      if (usedNames.has(camel)) {
        console.warn(`    Custom-vs-Custom name collision on "${camel}" (${baseName}); skipping`)
        continue
      }
    }
    const { viewportWidth, viewportHeight, paths } = parseCustomSvg(customSvgs[baseName])
    if (paths.length === 0) {
      console.warn(`    Skipping ${baseName}: no <path> elements`)
      continue
    }
    const code = generateCustomKotlin(camel, pascal, viewportWidth, viewportHeight, paths)
    fs.writeFileSync(path.join(TMP_DIR, `${pascal}.kt`), code)
    usedNames.add(camel)
    customCount++
  }

  // Atomic swap: replace BUILD_DIR with TMP_DIR only after a successful generation.
  if (fs.existsSync(BUILD_DIR)) {
    fs.rmSync(BUILD_DIR, { recursive: true, force: true })
  }
  fs.renameSync(TMP_DIR, BUILD_DIR)

  console.log(`  Wrote ${lucideCount} Lucide + ${customCount} Custom icon files`)
}

module.exports = { buildIcons }
